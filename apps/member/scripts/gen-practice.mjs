// Generates supabase/practice.sql from the app's practice catalog (src/data/practice.ts), so the database's
// skills and drills match what the app shows. The file upserts, so it can be run again on the hosted project
// whenever drills change; drills taken out of the app are marked inactive rather than deleted (logged activities
// point at them). Usage: npm run gen:practice

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import ts from 'typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const out = path.resolve(app, '../../supabase/practice.sql');

const src = fs.readFileSync(path.join(app, 'src/data/practice.ts'), 'utf8');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
vm.runInNewContext(js, { module: mod, exports: mod.exports, require: () => ({}) });
const { SKILLS, DRILLS } = mod.exports;

const q = (v) => (v === undefined || v === null ? 'null'
  : Array.isArray(v) ? `'{${v.map((x) => `"${String(x).replace(/'/g, "''").replace(/"/g, '\\"')}"`).join(',')}}'`
  : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = (list) => list.map((r) => `  (${r.map(q).join(', ')})`).join(',\n');
const updates = (cols) => cols.map((c) => `${c} = excluded.${c}`).join(', ');

const skillCols = ['id', 'label', 'balance', 'why', 'traits', 'path_id', 'class_ids', 'aliases', 'trainer_led', 'sort'];
const drillCols = ['id', 'skill_id', 'title', 'minutes', 'setting', 'level', 'activity', 'image', 'goal', 'needs', 'steps', 'good', 'stop_if', 'sort', 'active'];

const sql = `-- GENERATED by apps/member/scripts/gen-practice.mjs from apps/member/src/data/practice.ts. Do not edit by hand.
-- The practice catalog for Log at home: skills and drills. Safe to run again on the hosted project.

insert into public.skills (${skillCols.join(', ')}) values
${rows(SKILLS.map((s, i) => [s.id, s.label, s.balance, s.why, s.traits, s.pathId, s.classIds, s.aliases, s.trainerLed, i * 10]))}
on conflict (id) do update set ${updates(skillCols.slice(1))};

insert into public.drills (${drillCols.join(', ')}) values
${rows(DRILLS.map((d, i) => [d.id, d.skillId, d.title, d.minutes, d.setting, d.level, d.activity, d.image, d.goal, d.needs, d.steps, d.good, d.stop, i * 10, true]))}
on conflict (id) do update set ${updates(drillCols.slice(1))};

update public.drills set active = false where id not in (${DRILLS.map((d) => q(d.id)).join(', ')});

-- Every dog's focus skills from its traits and training paths (new dogs get theirs from a trigger).
select public.seed_focus_skills(id) from public.dogs;
`;

fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${SKILLS.length} skills, ${DRILLS.length} drills.`);
