// Writes supabase/migrations/20261014000100_breeds.sql from the app's breed list (src/data/breeds.ts), so the
// database and the app's offline mode match breeds the same way. That migration is already applied on the
// hosted project: when the list changes, write the changes in a new migration instead of re-running this.
// Usage: node scripts/gen-breeds.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import ts from 'typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const out = path.resolve(app, '../../supabase/migrations/20261014000100_breeds.sql');

const src = fs.readFileSync(path.join(app, 'src/data/breeds.ts'), 'utf8');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
vm.runInNewContext(js, { module: mod, exports: mod.exports });
const { BREEDS, APTITUDE_LABEL } = mod.exports;

const q = (v) => (Array.isArray(v) ? `'{${v.map((x) => `"${x.replace(/'/g, "''")}"`).join(',')}}'` : `'${String(v).replace(/'/g, "''")}'`);

const sql = `-- Breed-specific classes, phase 1: the breed list. GENERATED by apps/member/scripts/gen-breeds.mjs from
-- apps/member/src/data/breeds.ts; later changes to the list go in a new migration.
--
-- Partners tag classes with aptitudes (herding, sighthound…), never single breeds, and PackPass owns the
-- mapping. A dog stores the ids of up to three breeds (dogs.breed_ids, …_class_fit_gates.sql); dogs.breed
-- keeps the display name for the partner dashboard's rosters.

create type public.aptitude as enum (${Object.keys(APTITUDE_LABEL).map((a) => `'${a}'`).join(', ')});
create type public.size_band as enum ('toy', 'small', 'medium', 'large', 'giant');

create table public.breeds (
  id text primary key,
  name text not null unique,
  aliases text[] not null default '{}',
  aptitudes public.aptitude[] not null check (cardinality(aptitudes) between 1 and 3),
  size public.size_band not null
);
alter table public.breeds enable row level security;
create policy breeds_read on public.breeds for select to anon, authenticated using (true);

insert into public.breeds (id, name, aliases, aptitudes, size) values
${BREEDS.map((b) => `  (${q(b.id)}, ${q(b.name)}, ${q(b.aliases)}, ${q(b.aptitudes)}, ${q(b.size)})`).join(',\n')};
`;

fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${BREEDS.length} breeds).`);
